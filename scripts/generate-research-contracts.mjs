import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const START = '// BEGIN GENERATED RESEARCH CONTRACTS';
const END = '// END GENERATED RESEARCH CONTRACTS';
const NAMES = {
  'source.schema.json': 'sourceSchema',
  'claim.schema.json': 'claimSchema',
  'research-plan.schema.json': 'planSchema',
  'claim-bundle.schema.json': 'claimBundleSchema',
  'verification-event.schema.json': 'verificationEventSchema',
  'report-map.schema.json': 'reportMapSchema',
  'conflict.schema.json': 'conflictSchema',
  'run-manifest.schema.json': 'runManifestSchema'
};

function pointer(value, fragment, reference) {
  if (!fragment || fragment === '#') return value;
  if (!fragment.startsWith('#/')) throw new Error(`Unresolved pointer ${reference}.`);
  return fragment.slice(2).split('/').reduce((item, part) => {
    const key = part.replace(/~1/g, '/').replace(/~0/g, '~');
    if (!item || !Object.hasOwn(item, key)) throw new Error(`Unresolved pointer ${reference}.`);
    return item[key];
  }, value);
}

function inline(schema, owner, schemas, trail = []) {
  if (Array.isArray(schema)) return schema.map((item) => inline(item, owner, schemas, trail));
  if (!schema || typeof schema !== 'object') return schema;
  if ('$ref' in schema) {
    const [filePart, fragment = ''] = schema.$ref.split('#');
    const target = filePart ? path.basename(filePart) : owner;
    const reference = filePart ? schema.$ref : `${owner}${schema.$ref}`;
    if (!schemas.has(target)) throw new Error(`Missing schema reference ${reference}.`);
    const key = `${target}#${fragment}`;
    if (trail.includes(key)) throw new Error(`Unsupported schema reference cycle ${[...trail, key].join(' -> ')}.`);
    const resolved = pointer(schemas.get(target), `#${fragment}`, reference);
    const siblings = Object.fromEntries(Object.entries(schema).filter(([key]) => key !== '$ref'));
    return { ...inline(resolved, target, schemas, [...trail, key]), ...inline(siblings, owner, schemas, trail) };
  }
  return Object.fromEntries(Object.entries(schema)
    .filter(([key]) => !['$schema', '$id', 'title', 'description', '$defs'].includes(key))
    .map(([key, value]) => [key, inline(value, owner, schemas, trail)]));
}

function generatedBlock(schemas) {
  const rendered = Object.entries(NAMES)
    .map(([file, name]) => `const ${name} = ${JSON.stringify(inline(schemas.get(file), file, schemas), null, 2)};`)
    .join('\n\n');
  return `${START}\n// Generated by scripts/generate-research-contracts.mjs; do not edit.\n${rendered}\n${END}`;
}

function generatedRegistry(schemas) {
  const records = [...schemas.values()];
  const find = (schema, key) => Object.values(schema.$defs ?? {}).find((value) => value.pattern?.startsWith(`^${key}`));
  const ids = {
    run_id: schemas.get('run-manifest.schema.json').properties.run_id.pattern,
    plan_id: find(schemas.get('research-plan.schema.json'), 'plan_')?.pattern,
    source_id: find(schemas.get('source.schema.json'), 'src_')?.pattern,
    claim_id: find(schemas.get('claim.schema.json'), 'clm_')?.pattern,
    verification_event_id: schemas.get('verification-event.schema.json').properties.verification_event_id.pattern,
    conflict_id: schemas.get('conflict.schema.json').properties.conflict_id.pattern,
    report_map_id: schemas.get('report-map.schema.json').properties.report_map_id.pattern,
    report_unit_id: schemas.get('report-map.schema.json').$defs.reportUnit.properties.report_unit_id.pattern
  };
  const enums = {
    materiality: schemas.get('claim.schema.json').$defs.materiality.enum,
    confidence: schemas.get('claim.schema.json').$defs.confidence.enum,
    outcome: schemas.get('verification-event.schema.json').$defs.outcome.enum,
    sourceType: schemas.get('source.schema.json').$defs.sourceType.enum
  };
  return `// Generated by scripts/generate-research-contracts.mjs; do not edit.\nexport const canonicalSchemas = ${JSON.stringify(records, null, 2)};\nexport const enumValues = ${JSON.stringify(enums, null, 2)};\nexport const idPatterns = ${JSON.stringify(ids, null, 2)};\n`;
}

function replaceBlock(workflow, block) {
  const first = workflow.indexOf(START);
  const last = workflow.indexOf(END);
  if (first === -1 || last === -1 || last < first) throw new Error('Workflow generated contract markers are missing.');
  return `${workflow.slice(0, first)}${block}${workflow.slice(last + END.length)}`;
}

export async function generateResearchContracts({ schemaDirectory = path.join(ROOT, 'research', 'schemas'), workflowPath = path.join(ROOT, '.claude', 'workflows', 'research-swarm.js'), registryPath = path.join(ROOT, 'scripts', 'lib', 'research-contracts.generated.mjs'), check = false } = {}) {
  const schemas = new Map();
  for (const file of (await readdir(schemaDirectory)).filter((name) => name.endsWith('.schema.json')).sort()) {
    const parsed = JSON.parse(await readFile(path.join(schemaDirectory, file), 'utf8'));
    if (!parsed.$id) throw new Error(`Schema ${file} is missing $id.`);
    if ([...schemas.values()].some((schema) => schema.$id === parsed.$id)) throw new Error(`Duplicate schema ID ${parsed.$id}.`);
    schemas.set(file, parsed);
  }
  for (const file of Object.keys(NAMES)) if (!schemas.has(file)) throw new Error(`Missing required schema ${file}.`);
  const expected = replaceBlock(await readFile(workflowPath, 'utf8'), generatedBlock(schemas));
  const actual = await readFile(workflowPath, 'utf8');
  const registry = generatedRegistry(schemas);
  let actualRegistry = '';
  try { actualRegistry = await readFile(registryPath, 'utf8'); } catch {}
  if (check) {
    if (actual !== expected || actualRegistry !== registry) throw new Error('Generated workflow contracts are stale. Run npm run contracts:generate.');
    return;
  }
  await writeFile(workflowPath, expected);
  await writeFile(registryPath, registry);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  generateResearchContracts({ check: process.argv.includes('--check') }).catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
