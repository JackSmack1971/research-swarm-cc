function normalizeVerificationEvents(sources, claims, conflicts, events) {
  const augmentedSources = sources.map((source) => ({ ...source })); const augmentedClaims = claims.map((claim) => ({ ...claim, supporting_evidence: [...claim.supporting_evidence], counter_evidence: [...claim.counter_evidence] })); const augmentedConflicts = conflicts.map((conflict) => ({ ...conflict, claim_ids: [...conflict.claim_ids], supporting_source_ids: [...conflict.supporting_source_ids] })); let nextSource = 1;
  const canonicalId = () => { while (augmentedSources.some(({ source_id }) => source_id === `src_ver_${nextSource}`)) nextSource += 1; return `src_ver_${nextSource++}`; };
  for (const event of events) {
    validateVerifierEvent(event, augmentedSources, augmentedClaims); const rewritten = new Map();
    for (const discovered of event.new_sources ?? []) { const existing = sourceMatch(discovered, augmentedSources); if (existing) rewritten.set(discovered.source_id, existing.source_id); else { const source = { ...discovered, source_id: canonicalId() }; augmentedSources.push(source); rewritten.set(discovered.source_id, source.source_id); } }
    const claim = augmentedClaims.find(({ claim_id }) => claim_id === event.claim_id); const contradictorySources = [];
    for (const evidence of event.new_evidence ?? []) { const canonicalEvidence = { ...evidence, source_id: rewritten.get(evidence.source_id) ?? evidence.source_id }; const destination = canonicalEvidence.relationship === "supports" ? claim.supporting_evidence : claim.counter_evidence; if (!evidenceExists(destination, canonicalEvidence)) destination.push(canonicalEvidence); if (canonicalEvidence.relationship === "contradicts") contradictorySources.push(canonicalEvidence.source_id); }
    if (contradictorySources.length) { const existing = augmentedConflicts.find((conflict) => conflict.claim_ids.includes(claim.claim_id)); if (existing) { existing.supporting_source_ids = [...new Set([...existing.supporting_source_ids, ...contradictorySources])]; existing.reason = `${existing.reason} ${event.proposed_conflict ?? "Verifier-added contradictory evidence."}`.trim(); } else augmentedConflicts.push({ conflict_id: `conf_${event.verification_event_id}`, claim_ids: [claim.claim_id], supporting_source_ids: contradictorySources, reason: event.proposed_conflict ?? "Verifier-added contradictory evidence requires adjudication.", practical_implication: "Do not rely on the claim without adjudication of the contradictory evidence.", status: "unresolved" }); }
  }
  return { sources: augmentedSources, claims: augmentedClaims, conflicts: augmentedConflicts, verification_events: events };
}
